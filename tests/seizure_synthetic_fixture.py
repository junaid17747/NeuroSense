"""Disposable D6 fixtures. TEST_ONLY reviews never authorize any clinical data.

The real frozen manifest is copied, then every source digest/size is replaced
with generated bytes. Only the network transport, available disk space and
temporary-directory persistence detection are simulated by the tests.
"""

import copy
import hashlib
import io
import json
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

import numpy as np

from seizure_research.ingestion import ingest_cohort
from seizure_research.preprocessing import ChannelMapping, make_age_config
from seizure_research.quality import QualityThresholds
from seizure_research.readiness import check_readiness
from seizure_research.schemas import AgeGroup
from seizure_research.staging import stage_approved_pilot
from seizure_research.training import AnnotationEvidenceManifest, PILOT_CHANNELS, PILOT_SEIZURE_FILES, PILOT_SPLITS
from test_seizure_ingestion import plan_fixture, summary_text
from test_seizure_processing import _edf

PROJECT = Path(__file__).resolve().parents[1]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def write_json(path, payload):
    path.write_text(json.dumps(payload, sort_keys=True, indent=2, allow_nan=False) + "\n")


class SyntheticPilot:
    def __init__(self, base: Path):
        self.root = base / "TEST_ONLY_staged"
        self.root.mkdir()
        template_root = base / "template"
        template_root.mkdir()
        plan = plan_fixture(template_root, subjects=tuple(PILOT_SPLITS), years=(10,) * 6)
        prototypes = {item["subject_id"]: item for item in plan["recordings"]}
        plan["recordings"] = []
        self.file_manifest = base / "TEST_ONLY_file_manifest.json"
        manifest = json.loads((PROJECT / "docs/chbmit_pilot_file_manifest.json").read_text())
        manifest["dataset"] = "TEST_ONLY generated EDFs; no clinical data or genuine approvals"
        self.payloads = {}
        # Same 18-channel/256-Hz schema as the pilot, only 90 generated seconds.
        header_size = 256 * (len(PILOT_CHANNELS) + 1)
        header = bytearray(_edf(labels=PILOT_CHANNELS, rates=(256,) * 18, duration=1)[:header_size])
        header[236:244] = b"90      "
        for index, entry in enumerate(manifest["recordings"]):
            relative = entry["path"]
            time = np.arange(90 * 256) / 256
            burst = (time >= 30) & (time < 40) if relative in PILOT_SEIZURE_FILES else np.zeros(len(time), bool)
            values = []
            for channel in range(18):
                physical = ((10 + index * 0.12) * np.sin(2 * np.pi * (8 + channel * .15) * time + channel * .4)
                            + burst * 20 * np.sin(2 * np.pi * 18 * time)
                            + .5 * np.sin(2 * np.pi * 1.4 * time + index))
                values.append(np.rint((physical + 100) * 65535 / 200 - 32768).astype("<i2"))
            data = np.stack(values).reshape(18, 90, 256).transpose(1, 0, 2).tobytes()
            content = bytes(header) + data
            self.payloads[relative] = content
            entry.update(expected_bytes=len(content), expected_sha256=sha(content))
            if relative in PILOT_SEIZURE_FILES:
                sidecar = f"TEST_ONLY fictitious event 30 40 for {relative}\n".encode()
                self.payloads[entry["sidecar_path"]] = sidecar
                entry.update(sidecar_expected_bytes=len(sidecar), sidecar_expected_sha256=sha(sidecar))
        for doc in manifest["patient_documents"]:
            entries = [item for item in manifest["recordings"] if item["patient"] == doc["patient"]]
            blocks = []
            for index, entry in enumerate(entries):
                summary = summary_text(Path(entry["path"]).name, labels=PILOT_CHANNELS,
                                       events=((30, 40),) if entry["path"] in PILOT_SEIZURE_FILES else (),
                                       end="00:01:30")
                blocks.append(summary if index == 0 else summary[summary.index("File Name:"):])
            content = "\n".join(blocks).encode()
            self.payloads[doc["summary_path"]] = content
            doc.update(expected_bytes=len(content), expected_sha256=sha(content))
            for entry in entries:
                item = copy.deepcopy(prototypes[doc["patient"]])
                item.update(edf_path=entry["path"], expected_signal_sha256=entry["expected_sha256"],
                            expected_summary_sha256=doc["expected_sha256"])
                item["montage"]["channels"] = list(PILOT_CHANNELS)
                item["channels"] = [{"source_index": i, "source_label": label,
                                     "action": "keep", "output_label": label}
                                    for i, label in enumerate(PILOT_CHANNELS)]
                plan["recordings"].append(item)
        sums = "".join(f"{sha(data)}  {name}\n" for name, data in sorted(self.payloads.items())).encode()
        self.payloads["SHA256SUMS.txt"] = sums
        manifest["checksum_manifest"]["expected_bytes"] = len(sums)
        manifest["expected_edf_bytes_total"] = sum(item["expected_bytes"] for item in manifest["recordings"])
        manifest["expected_staged_bytes_total"] = sum(map(len, self.payloads.values()))
        write_json(self.file_manifest, manifest)
        self.plan = plan
        self.approval_path = self.root / "faculty-approval.json"
        self.approval = json.loads((PROJECT / "docs/chbmit_pilot_approval_record_template.json").read_text())
        for key in self.approval:
            if key.endswith("_status"):
                self.approval[key] = "approved"
            elif key.endswith(("_reviewed_on", "_approved_on")):
                self.approval[key] = "2026-10-12"
            elif key.endswith(("_reviewer", "_approver", "_ref")):
                self.approval[key] = "TEST_ONLY synthetic decision; not human approval"
        self.approval.update(institutional_determination="not_required", staging_root=str(self.root),
                             storage_persistence_confirmed=True, storage_policy_ref="TEST_ONLY disposable fixture",
                             staging_manifest_sha256=sha(self.file_manifest.read_bytes()))
        write_json(self.approval_path, self.approval)

    def transport(self, request, timeout):
        relative = request.full_url.removeprefix("https://physionet.org/files/chbmit/1.0.0/")
        if relative not in self.payloads:
            raise AssertionError("Attempt to fetch bytes outside synthetic allowlist")
        data = self.payloads[relative]
        result = io.BytesIO(data)
        result.status = 200
        result.headers = {"Content-Length": str(len(data))}
        return result

    def stage(self):
        with patch("seizure_research.staging.urllib.request.urlopen", side_effect=self.transport) as transport:
            result = stage_approved_pilot(self.root, self.file_manifest, self.approval_path)
        return result, transport.call_count

    def review(self):
        result = ingest_cohort(self.root, self.plan)
        if result.manifest is None:
            raise AssertionError(result.audit.model_dump_json())
        self.cohort = result.manifest
        mappings = tuple(ChannelMapping(source_index=i, source_label=label, target_label=label,
                                        expected_source_rate_hz=256)
                         for i, label in enumerate(PILOT_CHANNELS))
        self.config = make_age_config(AgeGroup.CHILD, mappings, target_sampling_rate_hz=256,
                                      research_review_ref="TEST_ONLY", line_noise_hz=None, step_seconds=1)
        self.config = self.config.model_copy(update={"quality_thresholds": QualityThresholds(window_seconds=5, step_seconds=1)})
        evidence = []
        for item in self.cohort.records:
            recording = item.recording
            sidecar = item.signal.relative_path + ".seizures" if recording.annotations else None
            evidence.append({
                "recording_id": recording.recording_id,
                "policy": "summary_sidecar_reconciled" if sidecar else "summary_zero_full_review",
                "summary_sha256": item.annotations.sha256, "sidecar_path": sidecar,
                "sidecar_sha256": sha(self.payloads[sidecar]) if sidecar else None,
                "coverage_start_seconds": 0, "coverage_end_seconds": 90,
                "events": [{"start_seconds": 30, "end_seconds": 40}] if sidecar else [],
                "reviewer": "TEST_ONLY", "reviewed_on": "2026-10-12",
                "evidence_ref": "TEST_ONLY_review",
                "reconciliation_ref": recording.provenance.annotation_provenance_ref,
                "complete_coverage_attested": True,
            })
        self.evidence = AnnotationEvidenceManifest.model_validate({"recordings": evidence})
        self.cohort_path = self.root / "cohort-manifest.json"
        self.config_path = self.root / "preprocessing.json"
        self.evidence_path = self.root / "annotation-evidence.json"
        for path, value in ((self.cohort_path, self.cohort), (self.config_path, self.config),
                            (self.evidence_path, self.evidence)):
            write_json(path, value.model_dump(mode="json"))
        self.approval["cohort_manifest_sha256"] = self.cohort.sha256
        write_json(self.approval_path, self.approval)

    def arguments(self):
        return dict(root=self.root, cohort_manifest_path=self.cohort_path,
                    preprocessing_config_path=self.config_path, annotation_evidence_path=self.evidence_path,
                    approval_record_path=self.approval_path, file_manifest_path=self.file_manifest)

    def readiness(self):
        return check_readiness(**self.arguments())


def synthetic_environment():
    """Only use inside TEST_ONLY TemporaryDirectory fixtures, never production."""
    from contextlib import ExitStack
    stack = ExitStack()
    stack.enter_context(patch("seizure_research.readiness.EPHEMERAL_ROOTS", ()))
    stack.enter_context(patch("shutil.disk_usage", return_value=SimpleNamespace(free=100 * 1024**3)))
    return stack
